#!/usr/bin/env python3
"""Regenerate the checked-in ISA index from AMD's public, MIT-licensed XML."""
import argparse
import hashlib
from pathlib import Path
import re
import xml.etree.ElementTree as ET
import zipfile

XML = "amdgpu_isa_rdna2.xml"
DIGEST = "d671ecbc36543674ab59e9b2feffd56718fd2137e7ad913c314f2e2508b9f4f7"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("spec", type=Path, help="AMD machine-readable ISA zip or extracted RDNA 2 XML")
parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "src/rdna2_catalog.inc")
args = parser.parse_args()
if zipfile.is_zipfile(args.spec):
    with zipfile.ZipFile(args.spec) as archive:
        data = archive.read(XML)
else:
    data = args.spec.read_bytes()
if hashlib.sha256(data).hexdigest() != DIGEST:
    parser.error("unexpected spec revision; expected the 2026-02-20 RDNA 2 XML")
root = ET.fromstring(data)
layouts = {n.findtext("EncodingName"): n for n in root.findall("ISA/Encodings/Encoding")}


def specimen(encoding, mnemonic):
    """One candidate encoding per identity. LLVM independently checks the decode."""
    name = encoding.findtext("EncodingName")
    layout = layouts[name]
    size = int(layout.findtext("BitCount"))
    fields = {f.findtext("FieldName"): sorted(f.findall("BitLayout/Range"), key=lambda r: int(r.get("Order")))
              for f in layout.findall("MicrocodeFormat/BitMap/Field")}
    code = int(layout.findtext("EncodingIdentifiers/EncodingIdentifier"), 2)
    def put(field, value):
        nonlocal code
        for r in fields.get(field, []):
            at, width = int(r.findtext("BitOffset")), int(r.findtext("BitCount"))
            mask = (1 << width)-1
            code = (code & ~(mask << at)) | ((value & mask) << at)
            value >>= width
    put("OP", int(encoding.findtext("Opcode")))
    defaults = {"VDST": 24, "VDATA": 24, "SDST": 24, "ADDR": 4, "VADDR": 4, "DATA0": 8, "DATA1": 10,
                "SBASE": 4, "SRSRC": 2, "SSAMP": 4, "SOFFSET": 128,
                "SIMM16": 0, "VSRC0": 4, "VSRC1": 6, "VSRC2": 8, "VSRC3": 10}
    values = {}
    for o in encoding.findall("Operands/Operand"):
        if o.get("IsImplicit") == "true":
            continue
        field, typ = o.findtext("FieldName"), o.findtext("OperandType")
        if typ=="OPR_EXEC":values[field]=126
        elif field in defaults:values[field]=defaults[field]
        elif field in ("SRC0","SRC1","SRC2"):
            j = int(field[-1])
            values[field] = 256+4+2*j if "VREG" in typ or "VGPR" in typ or (typ in ("OPR_SRC","OPR_SRC_NOLDS") and
                            (not mnemonic.startswith("v_permlane") or j==0)) else 4+2*j
        elif field in ("SSRC0","SSRC1"):
            values[field] = 4+2*int(field[-1])
    if name=="ENC_MIMG":values.update(DIM=1,DMASK=1)
    if name=="ENC_FLAT":values["SADDR"]=125
    if mnemonic.startswith(("image_load","image_store","image_atomic")):values["UNORM"]=1
    if mnemonic.startswith("image_bvh"):values.update(UNORM=1,DIM=0,DMASK=15,R128=1)
    if mnemonic.startswith("ds_gws") or mnemonic=="ds_ordered_count":values["GDS"]=1
    for k,v in values.items():put(k,v)
    # Encodings that accept more than one opcode value (e.g. EXP has none)
    # still retain the vendor's fixed encoding identifier.
    if size%32 or size>96:raise ValueError(f"unexpected base encoding {name}")
    return size//8, [(code>>(32*i)) & 0xffffffff for i in range(3)]


rows = {}
for ins in root.findall("ISA/Instructions/Instruction"):
    name = ins.findtext("InstructionName").lower()
    enc = ins.findall("InstructionEncodings/InstructionEncoding")
    family = enc[0].findtext("EncodingName").removeprefix("ENC_")
    group = ins.findtext("FunctionalGroup/Name")
    if name in rows or not all(re.fullmatch(r"\w+", v) for v in (name, family, group)):
        raise ValueError(f"bad spec entry: {name}")
    flags = sum(1 << i for i, flag in enumerate(("IsBranch", "IsConditionalBranch", "IsIndirectBranch", "IsProgramTerminator"))
                if ins.findtext("InstructionFlags/"+flag) == "TRUE")
    size,words=specimen(enc[0],name)
    bits=",".join(f"0x{n:08x}u" for n in words)
    rows[name] = f'    {{"{name}","{family}","{group}",{len(enc)},{flags},{size},{{{bits}}}}},\n'
if len(rows) != 1153:
    raise ValueError("incomplete instruction table")
args.out.write_text("// Generated by tools/rdna2_catalog.py from AMD RDNA 2 XML, 2026-02-20.\n"
                    "// Copyright (c) 2026 Advanced Micro Devices, Inc., or its affiliates. MIT license.\n"
                    + "".join(rows[n] for n in sorted(rows)))
